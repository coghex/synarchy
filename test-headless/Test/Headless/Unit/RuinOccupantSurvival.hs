-- | Ruin occupant survival (#2754).
--
--   A ruin_small occupant is a persistent encounter member (#916) whose
--   death clears the encounter. Its survival physiology used to run like
--   an acolyte's with nothing to sustain it, so an unvisited occupant on
--   the reported seed-14 world went delirious from hyponatremia and died
--   of electrolyte imbalance — clearing an encounter nobody fought. Enemy
--   definitions are now exempt from survival physiology
--   (@scripts\/unit_survival_exempt.lua@); this group proves the
--   exemption holds in the reported world, and the nested "survival
--   exemption" group ("Test.Headless.Unit.SurvivalExemption") pins its
--   edges unit by unit.
--
--   On the pre-fix physiology this same fixture fails the way the report
--   did: the occupant is delirious (salt_conc about 0.54, the salt
--   imbalance meter filling) roughly 700 to 1,000 engine seconds after
--   its creation, in both the early and the late case.
--
--   __What is real here.__ The world is the #2640 gate's own: seed 14,
--   size 64, 3 plates, page @expedition@, identity @First Expedition@,
--   generated by the real world thread with the shipped content
--   registries loaded. Ruin instance 4 is the reported occupied ruin.
--   Its occupants are created by the production location-stamp hook
--   (@scripts\/location_stamper.lua@), which rolls the roster, calls
--   @unit.spawn@ and registers every occupant on the placed instance;
--   the spawn command then runs through the real unit tick. Nothing
--   else is on the page and nothing wounds the occupants: the run is
--   unfought, which the observer checks.
--
--   __How time moves.__ The bound is simulation time, so it is stepped
--   rather than waited for. Every step advances a scripted clock by
--   'stepDt' and runs, in production order, the real unit tick
--   ('Unit.Thread.unitTickWith': commands, the engine clock, movement,
--   publication), then the real @unit_resources.update@ (physiology)
--   and @unit_ai.update@ (decisions) — the two scripts the shipped
--   @init_loader.lua@ schedules every 0.1 s, which is 'stepDt'. Nothing
--   in the fixture writes a stat or stubs an action; elapsed time per
--   occupant is the sum of the steps since the unit tick first reported
--   it alive.
--
--   After the bound the roster is killed, and the encounter must then
--   clear: the production clearance evaluator (the world thread's
--   @tickLocationDiscovery@) was live throughout, so "never cleared"
--   was an observation rather than an evaluator that never ran.
--
--   The world calendar is advanced by the world thread's own clock, not
--   by these steps, so "world age" in the late case means elapsed
--   engine seconds ('engine.gameTime'), the clock the issue measures.
--
--   __Local opt-in only (#2809).__ The two scenarios are actual game
--   simulations (10,800 engine seconds per occupant on a generated
--   world), and owner decision z3hd4feg (2026-10-08) makes those
--   optional, local only and never CI. They register no examples unless
--   @SYNARCHY_RUIN_SURVIVAL=1@ is set; any other value, or none,
--   registers nothing, and @SYNARCHY_FULL_TESTS@ does not enable them.
--   Neither CI nor @tools/ci-local.sh@ sets the variable. The nested
--   "survival exemption" group is finite and stays unconditional, so it
--   runs wherever this parent group runs. Run the two scenarios locally:
--
--   > SYNARCHY_RUIN_SURVIVAL=1 cabal-3.16.1.0 test synarchy-test-headless \
--   >   --test-options='--match "ruin occupant survival (#2754)"'
