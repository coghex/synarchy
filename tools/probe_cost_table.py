#!/usr/bin/env python3
"""Export the quruntul lab's per-probe wall times to `docs/probe_costs.json` (#2947).

A review of which probes earn their runtime (`docs/probe_value_findings.md`,
PRB-14) had to rebuild its cost data from the lab's local ledger every time:
the ledger (`<git-common-dir>/quruntul/ledger.sqlite3`) is untracked, and
`docs/probe_census.json` is the wrong home (its writer refuses CI-eligible
probes and it records owner policy). This tool reads the ledger and writes a
tracked, deterministic table, so the next review starts from the last one.

What a row holds, for every key of the LIVE `probe_runner_registry.PROBES`
(deferred, opt-in and direct-only probes included; the adapter's scheduling
exclusions do not remove rows):

* the most recent sample: wall seconds, state, revision (12-character sha),
  run id and UTC date; and
* across all samples: the count and the minimum, median and maximum seconds.

A probe the lab never ran has explicit nulls (and a count of 0), never a guess.

Samples
-------
A sample is a finished lab trial of the probe's suite (`probe:` plus the key
with underscores replaced by hyphens, the adapter's `_suite_id` convention)
whose state is `passed`, `failed` or `timeout`, whose recorded
`duration_seconds` is finite and non-negative, and whose recorded `finished`
instant parses. Pending, running, blocked, crashed, interrupted and
harness-error trials are not execution samples and are never turned into
fabricated failures. A shakedown run covers many suites, so a trial's suite is
the one its own document names, falling back to its run's suite.

The reported state is the lab's interpreted result: `timeout` only when the
lab recorded one (never inferred from elapsed time); `failed` when the trial
failed OR any per-check result of that trial is `failed` or `missing` (a
protocol probe can exit zero with a failed check); otherwise `passed`.

"Most recent" is by the trial's recorded `finished` instant, then its
`started` instant, then the run id, then the trial number, so ties break
deterministically. Revision and date come from ledger provenance (the run's
revision and the trial's `finished`), never from this checkout or the clock.

The figures are recorded lab-trial wall-clock seconds, one trial each at the
time it ran, on the lab machine. They include engine boot and may include
resource waits (a trial can wait for a machine-wide lock). They are not
guaranteed contention-free and are not CI timings.

The ledger is opened read-only as one consistent snapshot and is never created
or modified here. A missing, unreadable or incompatible ledger fails with a
message and leaves the tracked table untouched. The output carries no
timestamp or machine path, so a rerun against the same ledger is
byte-identical.

Usage:
  python3 tools/probe_cost_table.py [--ledger PATH] [--output PATH] [--stdout]

The ledger path defaults to `PROBE_COST_LEDGER` if set, otherwise
`<git-common-dir>/quruntul/ledger.sqlite3`.
Exit codes: 0 = written, 2 = the ledger could not be read.
"""
from __future__ import annotations

import argparse
import datetime
import json
import math
import os
import sqlite3
import statistics
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import probe_runner_registry  # noqa: E402

SCHEMA = "probe-costs/v1"
DEFAULT_OUTPUT = ROOT / "docs" / "probe_costs.json"
LEDGER_ENV = "PROBE_COST_LEDGER"
SAMPLE_STATES = ("passed", "failed", "timeout")
FAILED_RESULTS = ("failed", "missing")
REVISION_LENGTH = 12
SECONDS_PLACES = 3

DESCRIPTION = (
    "Per-probe wall-clock seconds recorded by the quruntul lab, generated by "
    "tools/probe_cost_table.py from the lab ledger. Each figure is the wall time "
    "of one recorded lab trial, run serially on the lab machine at the time; it "
    "includes engine boot and may include waits for machine-wide resources, so it "
    "is not guaranteed contention-free and is not a CI timing. 'latest' is the "
    "most recent sample; the other statistics span every sample. A probe the lab "
    "never ran has null figures and a count of 0."
)

COLUMNS = {
    "runs": ("id", "suite", "revision"),
    "trials": ("run_id", "number", "state", "document"),
    "results": ("run_id", "number", "outcome"),
}


class LedgerError(Exception):
    """The ledger cannot be turned into a table; nothing is written."""


def suite_id(key: str) -> str:
    """The adapter's suite id for a registry key (`.quruntul/adapter.py::_suite_id`)."""
    return "probe:" + key.replace("_", "-")


def default_ledger() -> Path:
    override = os.environ.get(LEDGER_ENV)
    if override:
        return Path(override)
    try:
        done = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--git-common-dir"],
                              capture_output=True, text=True, check=True, timeout=60)
    except (OSError, subprocess.SubprocessError) as error:
        raise LedgerError(f"cannot locate the git common directory: {error}") from error
    common = Path(done.stdout.strip())
    if not common.is_absolute():
        common = ROOT / common
    return common / "quruntul" / "ledger.sqlite3"


def _instant(value) -> datetime.datetime | None:
    if not isinstance(value, str):
        return None
    try:
        parsed = datetime.datetime.fromisoformat(value)
    except ValueError:
        return None
    if parsed.tzinfo is None:
        return None
    return parsed.astimezone(datetime.timezone.utc)


def read_trials(ledger: Path) -> list[dict]:
    """Every trial row with its run's provenance and its per-check result outcomes.

    One read transaction, so the three tables agree. Raises LedgerError."""
    if not ledger.is_file():
        raise LedgerError(f"no lab ledger at {ledger}")
    try:
        db = sqlite3.connect(f"file:{ledger}?mode=ro", uri=True)
    except sqlite3.Error as error:
        raise LedgerError(f"cannot open the ledger {ledger}: {error}") from error
    try:
        db.execute("PRAGMA query_only = ON")
        db.execute("BEGIN")
        for table, wanted in COLUMNS.items():
            have = {row[1] for row in db.execute(f"PRAGMA table_info({table})")}
            if not set(wanted) <= have:
                raise LedgerError(f"the ledger {ledger} is incompatible: table {table!r} lacks "
                                  f"{sorted(set(wanted) - have) or 'columns'}")
        failed_results = set()
        for run_id, number in db.execute(
                "SELECT DISTINCT run_id, number FROM results WHERE outcome IN (%s)"
                % ",".join("?" * len(FAILED_RESULTS)), FAILED_RESULTS):
            failed_results.add((run_id, number))
        rows = db.execute(
            "SELECT t.run_id, t.number, t.state, t.document, r.suite, r.revision "
            "FROM trials t JOIN runs r ON r.id = t.run_id").fetchall()
        db.execute("COMMIT")
    except sqlite3.Error as error:
        raise LedgerError(f"cannot read the ledger {ledger}: {error}") from error
    finally:
        db.close()
    trials = []
    for run_id, number, state, document, run_suite, revision in rows:
        try:
            doc = json.loads(document)
        except (TypeError, ValueError) as error:
            raise LedgerError(f"the ledger {ledger} is incompatible: trial {run_id}/{number} "
                              f"has an unreadable document") from error
        if not isinstance(doc, dict):
            raise LedgerError(f"the ledger {ledger} is incompatible: trial {run_id}/{number} "
                              f"has a non-object document")
        trials.append(dict(run_id=run_id, number=number, state=state, doc=doc, run_suite=run_suite,
                           revision=revision, failed_check=(run_id, number) in failed_results))
    return trials


def _sample(trial: dict) -> dict | None:
    """The execution sample a trial contributes, or None when it contributes none."""
    if trial["state"] not in SAMPLE_STATES:
        return None
    doc = trial["doc"]
    seconds = doc.get("duration_seconds")
    if isinstance(seconds, bool) or not isinstance(seconds, (int, float)):
        return None
    if not math.isfinite(seconds) or seconds < 0:
        return None
    finished = _instant(doc.get("finished"))
    if finished is None:
        return None
    started = _instant(doc.get("started")) or finished
    if trial["state"] == "timeout":
        state = "timeout"
    elif trial["state"] == "failed" or trial["failed_check"]:
        state = "failed"
    else:
        state = "passed"
    return dict(
        seconds=float(seconds), state=state, finished=finished,
        order=(finished, started, str(trial["run_id"]), trial["number"]),
        revision=str(trial["revision"])[:REVISION_LENGTH], run_id=trial["run_id"],
        date=finished.date().isoformat())


def build_table(trials: list[dict], keys: list[str]) -> dict:
    """The `probe-costs/v1` document for `keys` from the ledger's `trials`."""
    by_suite = {suite_id(key): key for key in keys}
    samples: dict[str, list[dict]] = {key: [] for key in keys}
    for trial in trials:
        key = by_suite.get(trial["doc"].get("suite") or trial["run_suite"])
        if key is None:
            continue
        sample = _sample(trial)
        if sample is not None:
            samples[key].append(sample)
    probes = {}
    for key in keys:
        found = samples[key]
        row = dict(wall_seconds=None, state=None, revision=None, run_id=None, date=None,
                   count=len(found), min_seconds=None, median_seconds=None, max_seconds=None)
        if found:
            latest = max(found, key=lambda s: s["order"])
            seconds = [s["seconds"] for s in found]
            row.update(
                wall_seconds=round(latest["seconds"], SECONDS_PLACES), state=latest["state"],
                revision=latest["revision"], run_id=latest["run_id"], date=latest["date"],
                min_seconds=round(min(seconds), SECONDS_PLACES),
                median_seconds=round(statistics.median(seconds), SECONDS_PLACES),
                max_seconds=round(max(seconds), SECONDS_PLACES))
        probes[key] = row
    return dict(schema=SCHEMA, description=DESCRIPTION, probes=probes)


def render(table: dict) -> str:
    return json.dumps(table, indent=2, sort_keys=True) + "\n"


def registry_keys() -> list[str]:
    return [key for key, _script, _description in probe_runner_registry.PROBES]


def write_atomically(path: Path, text: str) -> None:
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    os.replace(temporary, path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--ledger", type=Path, help="the lab ledger (default: $%s or the git common dir's)" % LEDGER_ENV)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="where to write (default: %(default)s)")
    parser.add_argument("--stdout", action="store_true", help="print the table instead of writing it")
    args = parser.parse_args(argv)
    try:
        ledger = args.ledger or default_ledger()
        text = render(build_table(read_trials(ledger), registry_keys()))
    except LedgerError as error:
        print(f"probe_cost_table: {error}", file=sys.stderr)
        return 2
    if args.stdout:
        sys.stdout.write(text)
    else:
        write_atomically(args.output, text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
